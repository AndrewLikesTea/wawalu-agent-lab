// Stamp the build with the commit it was built from.
//
// WHY THIS EXISTS. `/healthz` could say the site was up; it could not say WHICH
// build was up. The only place that answer exists at build time is the git
// checkout the build ran against, so it is written down here, once, into a
// versioned file the deployed Pages Function and the shipped page both import
// (src/build-stamp.js). Nothing reads a dashboard value, a deploy-log line, or
// an environment variable that preview and production could set differently:
// the stamp travels inside the artifact, so the artifact answers for itself.
//
// THE ONE RULE. A sha is only ever written when git actually returned one. Where
// the checkout has no git metadata — a tarball, a shallow export, a container
// without git — the stamp is written with `commitSha: null`, the explicit
// "unstamped" marker, and the build carries on. It never fabricates a sha and it
// never fails the build: an unstamped build must still deploy, and must still
// say out loud on `/healthz` that it is unstamped.
//
// WHY A .js MODULE AND NOT .json. Everything that reads this file is also
// bundled into the Pages Functions worker. A plain ES module is the one form the
// Functions bundler, the browser, and `node --test` all accept with no import
// attribute, so there is no environment where the stamp resolves in tests and
// fails to resolve in the deployed worker.
//
// It writes exactly one file inside this repository, reads no credential, and
// touches no deployment path.

import { execFile } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { promisify } from "node:util";
import { pathToFileURL } from "node:url";

const run = promisify(execFile);
const root = resolve(import.meta.dirname, "..");

export const STAMP_PATH = resolve(root, "src", "build-stamp.js");
export const SCHEMA_VERSION = 1;

/** The full sha of HEAD, or null when git cannot answer. Never throws. */
export async function headCommitSha({ git = run, cwd = root } = {}) {
  try {
    const { stdout } = await git("git", ["rev-parse", "HEAD"], { cwd });
    const sha = String(stdout ?? "").trim().toLowerCase();
    return /^[0-9a-f]{40}$/.test(sha) ? sha : null;
  } catch {
    return null;
  }
}

/** The module source, so the written file is reviewable as text, not as data. */
export function stampSource({ commitSha, builtAt }) {
  return `// GENERATED by scripts/write-build-stamp.mjs on every \`npm run build\`.
// Do not edit by hand: the next build overwrites it. It is committed with
// \`commitSha: null\` so a checkout never claims a build it did not make;
// \`null\` is the explicit "this build is unstamped" marker, which
// src/release-build-match.js turns into the \`unknown\` verdict \`/healthz\`
// reports with reason \`no_build_stamp\`.
export const BUILD_STAMP = Object.freeze({
  schemaVersion: ${SCHEMA_VERSION},
  commitSha: ${commitSha === null ? "null" : JSON.stringify(commitSha)},
  builtAt: ${builtAt === null ? "null" : JSON.stringify(builtAt)},
});

export default BUILD_STAMP;
`;
}

/**
 * Write the stamp for this build.
 *
 * `now` and `git` are injectable so a test can assert both the stamped and the
 * unstamped path without a clock and without a repository.
 */
export async function writeBuildStamp({ path = STAMP_PATH, git = run, cwd = root, now = () => new Date() } = {}) {
  const commitSha = await headCommitSha({ git, cwd });
  const builtAt = commitSha === null ? null : now().toISOString();
  await writeFile(path, stampSource({ commitSha, builtAt }));
  return { commitSha, builtAt, path };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const stamp = await writeBuildStamp();
  console.log(`stamped build ${stamp.commitSha ?? "unknown (no git metadata)"} at ${stamp.builtAt ?? "an unrecorded time"}`);
}
