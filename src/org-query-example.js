// The bundled synthetic organizational query sample.
//
// WHY A SECOND EXAMPLE FILE. `query-sample-example.js` is a *template*: nine
// rows, three units, three day buckets, sized so a gateway owner can read the
// whole thing and see which column means what. Every publishable floor refuses
// it, which is correct for a template and useless as a demonstration — a visitor
// who grades it meets the honest "nothing here is gradeable yet" state and never
// sees what a graded organizational reading looks like.
//
// This module is that demonstration: one invented multi-department sample large
// enough to clear the floors `prompt-grading-eligibility.js` publishes, so the
// front door can show the coaching decision itself rather than only its refusal.
// The template is untouched and stays the thing a reader downloads.
//
// THREE RULES, ALL ASSERTED IN tests/org-query-decision.test.js:
//   1. The bytes below go through `parseQuerySample` — the shipped validator,
//      never a bypass. If the contract tightens, this example fails with it.
//   2. Every `org_unit_id` is an active department in the bundled HRIS export,
//      read from `exampleDepartmentUnitIds()` rather than spelled again here.
//   3. It is deterministic. No clock, no randomness: the day buckets are fixed
//      strings and every token count is arithmetic on the row index, so two page
//      loads produce identical bytes and therefore an identical input digest.
//
// Everything is invented. No real company, person, prompt, model, or provider
// identifier appears here, and nothing in this file reaches a network.

import { parseQuerySample } from "./query-sample-contract.js";
import { exampleDepartmentUnitIds } from "./query-sample-example.js";

/** The example as a file, in the shape the import surface already accepts. */
export const EXAMPLE_ORG_QUERY_SAMPLE_FILE = Object.freeze({
  fileName: "example-organizational-query-sample.csv",
  mediaType: "text/csv",
});

/** What a reader is told this file is, wherever it is named on the page. */
export const EXAMPLE_ORG_QUERY_PROVENANCE = Object.freeze({
  label: "Bundled synthetic organizational query sample",
  detail: "Invented rows generated in this tab from a fixed recipe — no gateway, provider, "
    + "customer, or employee data. It is graded by exactly the modules a reader's own file is.",
});

const HEADER = Object.freeze([
  "org_unit_id", "query_date", "model", "input_tokens", "output_tokens",
  "prompt_excerpt", "category",
]);

/**
 * Eighteen consecutive day buckets, fixed rather than derived from a clock.
 *
 * Eighteen because the history floor is fourteen: a sample that only just clears
 * a floor demonstrates the floor, not the reading. Generated by arithmetic on
 * one hard-coded UTC midnight, so the list is a function of this file alone.
 */
const FIRST_DAY = Date.UTC(2026, 5, 1);
const MS_PER_DAY = 86_400_000;
const DAYS = Object.freeze(Array.from({ length: 18 },
  (_, index) => new Date(FIRST_DAY + index * MS_PER_DAY).toISOString().slice(0, 10)));

const MODELS = Object.freeze(["acme-sonnet-1", "acme-opus-1", "acme-haiku-1"]);

/**
 * Two invented excerpts, so the local-classifier path is exercised and not only
 * the declared-category one. Kept few on purpose: an excerpt the classifier
 * declines lowers the classified share a reader is shown, and the point of this
 * sample is a high-confidence reading with a visible unclassified remainder.
 */
const EXCERPTS = Object.freeze([
  "draft the rollback steps for the storage migration and list the checks",
  "make this shorter",
]);

/**
 * One recipe per department: how many queries of each rubric category it asked.
 *
 * The mixes differ deliberately, and that is the whole demonstration — five
 * units with the same mix would grade identically and the priority list a leader
 * is meant to read would be alphabetical noise. `excerpts` is how many of the
 * unit's rows carry an excerpt instead of a declared category.
 */
const RECIPES = Object.freeze([
  Object.freeze({ highValue: 19, inefficient: 6, overProvisioned: 4, outOfScope: 2, excerpts: 2 }),
  Object.freeze({ highValue: 14, inefficient: 8, overProvisioned: 5, outOfScope: 3, excerpts: 2 }),
  Object.freeze({ highValue: 10, inefficient: 12, overProvisioned: 6, outOfScope: 4, excerpts: 2 }),
  Object.freeze({ highValue: 7, inefficient: 11, overProvisioned: 8, outOfScope: 5, excerpts: 2 }),
  Object.freeze({ highValue: 5, inefficient: 14, overProvisioned: 9, outOfScope: 6, excerpts: 2 }),
]);

const CATEGORY_ORDER = Object.freeze(["highValue", "inefficient", "overProvisioned", "outOfScope"]);

/**
 * The rows one unit contributes, in the order they are written.
 *
 * The day is `index * 5` modulo eighteen: five and eighteen share no factor, so
 * every bucket is used before any repeats and the window is the full span rather
 * than a clump. Nothing here reads a clock or a random source.
 */
function unitRows(unitId, recipe, seed) {
  const rows = [];
  const push = (excerpt, category) => {
    const index = rows.length + seed;
    rows.push([
      unitId,
      DAYS[(index * 5) % DAYS.length],
      MODELS[index % MODELS.length],
      String(400 + ((index * 37) % 1600)),
      String(200 + ((index * 23) % 900)),
      excerpt,
      category,
    ]);
  };
  for (const category of CATEGORY_ORDER) {
    for (let count = 0; count < (recipe[category] ?? 0); count += 1) push("", category);
  }
  for (let count = 0; count < recipe.excerpts; count += 1) {
    push(EXCERPTS[count % EXCERPTS.length], "");
  }
  return rows;
}

/** The example as bytes, in the delimited dialect the query-sample contract reads. */
export function exampleOrgQuerySampleText() {
  const units = exampleDepartmentUnitIds();
  const lines = [HEADER.join(",")];
  units.slice(0, RECIPES.length).forEach((unitId, index) => {
    for (const row of unitRows(unitId, RECIPES[index], index * 7)) lines.push(row.join(","));
  });
  return `${lines.join("\n")}\n`;
}

/** The example as a file, in the `{ fileName, mediaType, text }` shape. */
export function exampleOrgQuerySampleFiles() {
  return [{ ...EXAMPLE_ORG_QUERY_SAMPLE_FILE, text: exampleOrgQuerySampleText() }];
}

/** Translate it with the real validator. There is no bypass branch. */
export function loadExampleOrgQuerySample() {
  return parseQuerySample(exampleOrgQuerySampleText());
}
