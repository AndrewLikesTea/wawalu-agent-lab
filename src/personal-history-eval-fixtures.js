/**
 * A name for each side of the one coverage boundary the product acts on.
 *
 * ASSUMPTION, and the reason this is a fixture-side label rather than a report
 * field: `PERSONAL_COVERAGE_FLOOR` is the only coverage number that changes a
 * published claim, so `sufficient` and `thin` are the only distinction that
 * carries weight. `full` is split out purely so a fixture can tell a perfect
 * read from a merely adequate one — a denominator bug that drops one entry is
 * invisible against a 0.75 floor and obvious against 1.0. No tier here feeds a
 * score; adding one that did would be a second threshold with no published
 * argument behind it.
 */
export const EVAL_COVERAGE_TIERS = Object.freeze([
  Object.freeze({ tier: "none", rule: "No prompt entries, so no denominator and no ratio." }),
  Object.freeze({ tier: "full", rule: "Every prompt entry scored." }),
  Object.freeze({
    tier: "sufficient",
    rule: `At or above the published coverage floor of ${PERSONAL_COVERAGE_FLOOR} and below 1.`,
  }),
  Object.freeze({
    tier: "thin",
    rule: `Below the published coverage floor of ${PERSONAL_COVERAGE_FLOOR}. Confidence in a `
      + "report drawn from this much of a file is downgraded one step.",
  }),
]);

export function evalCoverageTier(coverage) {
  const ratio = coverage?.ratio ?? null;
  if (ratio === null) return "none";
  if (ratio === 1) return "full";
  return ratio >= PERSONAL_COVERAGE_FLOOR ? "sufficient" : "thin";
}

// ---------------------------------------------------------------------------
// Trend across benchmark periods
// ---------------------------------------------------------------------------

/**
 * The direction of the leading move across consecutive benchmark periods.
 *
 * WHAT IS COMPARED, and why it is not the points. Points scale with how many
 * prompts a period holds, so a quiet month would read as an improvement. The
 * comparable figure is the leading move's points per scored prompt: what that
 * one habit costs on an average request.
 *
 * WHEN NO TREND IS REPORTED. If the leading move is not the same move in every
 * period there is no series to compare — two different habits' costs are not
 * points on one line — and the direction is `move_changed`. This refuses the
 * most tempting wrong chart in the product.
 *
 * WHAT IT IS NOT. It is still one person's own history, so a direction here is
 * never a comparison to anybody: `improving` means this person's leading habit
 * costs less per request than it did, and nothing else. A period sitting at the
 * eligibility floor carries low confidence by the published tiers, and stacking
 * three low-confidence readings does not produce a confident trend — which is
 * why this returns an arithmetic direction and no confidence level of its own.
 */
export function evalPeriodTrend(reports) {
  const series = reports.map((report, at) => Object.freeze({
    period: at + 1,
    moveId: report.priority.id,
    points: report.priority.points,
    scoredPrompts: report.coverage.scoredPrompts,
    pointsPerScoredPrompt: report.coverage.scoredPrompts
      ? roundTo(report.priority.points / report.coverage.scoredPrompts, 2) : null,
    confidence: report.confidence.level,
  }));
  const moveId = series[0]?.moveId ?? null;
  if (!moveId || !series.every((entry) => entry.moveId === moveId)) {
    return Object.freeze({ moveId: null, direction: "move_changed", series: Object.freeze(series) });
  }
  const values = series.map((entry) => entry.pointsPerScoredPrompt);
  const falling = values.every((value, at) => at === 0 || value < values[at - 1]);
  const rising = values.every((value, at) => at === 0 || value > values[at - 1]);
  const flat = values.every((value) => value === values[0]);
  return Object.freeze({
    moveId,
    direction: flat ? "flat" : falling ? "improving" : rising ? "worsening" : "mixed",
    series: Object.freeze(series),
  });
}

