// The evaluation fixtures for the personal AI-history report: labelled prompts,
// exports generated from them, and the figure every export is expected to
// produce, stated before the code is run.
//
// WHY A SECOND FIXTURE MODULE. `personal-history-fixture.js` is the canonical
// preview: one invented person, shown to readers, built to look like a real
// week. It is deliberately not a scoring fixture — its numbers move whenever a
// prompt in it is reworded, which is the right trade for a preview and the wrong
// one for a grade. This module is the other half: exports assembled from a small
// set of *labelled* prompts whose rubric output is written down here as data, so
// every published figure below is arithmetic a reviewer can redo by hand on this
// page rather than a number recorded from a run.
//
// EVERYTHING HERE IS SYNTHETIC. The prompt texts are the bundled preview's
// hand-authored requests, reused rather than re-invented so no second corpus can
// drift from the first. No real provider export, account, conversation,
// customer, or telemetry data was available to this workflow and none is used.
// No fixture file is committed: every export is generated by the functions
// below.
//
// THE ONE ASSUMPTION EVERY EXPECTATION RESTS ON. A personal history is graded
// one prompt at a time — `buildPersonalHistoryReport` hands each entry to
// `gradeMyPrompt` on its own — so a single prompt is a single-turn grade and its
// turn share is 1. That makes a move's points across a history the exact product
// of one prompt's points and the number of prompts carrying it, with no
// weighting of any kind in between. `EVAL_PROMPT_LABELS` records one prompt's
// points; every total below is a multiplication of them, and
// tests/personal-history-evaluation.test.js checks both halves separately: that
// the labels still match the classifier, and that the reader's totals still
// match the labels.

