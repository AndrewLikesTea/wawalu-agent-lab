// ---------------------------------------------------------------------------
// Expected totals, computed from the labels
// ---------------------------------------------------------------------------

/**
 * The ranking a composition produces, derived from `EVAL_PROMPT_LABELS` alone.
 *
 * This is a second implementation of the published ranking rule, written from
 * the contract's words rather than shared with the reader's code, so a test
 * comparing the two is an agreement check and not a tautology.
 *
 * @param {ReadonlyArray<{prompt: string, count: number}>} blocks
 * @returns {ReadonlyArray<{id, kind, axis, points, promptsAffected}>} highest first.
 */
export function expectedRanking(blocks) {
  const tally = new Map();
  for (const block of blocks) {
    for (const entry of LABEL[block.prompt].moves) {
      const row = tally.get(entry.id)
        ?? { id: entry.id, kind: entry.kind, axis: entry.axis, points: 0, promptsAffected: 0 };
      row.points += entry.points * block.count;
      row.promptsAffected += block.count;
      tally.set(entry.id, row);
    }
  }
  return Object.freeze([...tally.values()]
    .map((row) => Object.freeze(row))
    .sort((left, right) => right.points - left.points
      || right.promptsAffected - left.promptsAffected
      || Number(right.kind === "fix") - Number(left.kind === "fix")
      || left.id.localeCompare(right.id)));
}

const roundTo = (value, decimals) => Math.round(value * 10 ** decimals) / 10 ** decimals;

/** The lead margin the contract defines, from the ranking above. */
export function expectedLeadMargin(ranking) {
  const [top, runnerUp] = ranking;
  return runnerUp ? roundTo((top.points - runnerUp.points) / top.points, 3) : 1;
}

