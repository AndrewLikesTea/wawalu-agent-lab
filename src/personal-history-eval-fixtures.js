/** `count` calendar days inside one month, so a period is obviously one period. */
export function evalDays(month, count) {
  return Object.freeze(Array.from({ length: count }, (unused, at) => `${month}-${String(at + 2).padStart(2, "0")}`));
}

/**
 * One conversation, in the nested spelling a real export uses: a titled
 * conversation carrying its own timestamp and a `messages` array, the reply the
 * assistant would have given, and the prompt itself split across `content.parts`
 * so the nested-parts branch of the reader is exercised rather than described.
 * The parts rejoin with the newline they were split on, so the graded text is
 * byte-identical to the label's.
 */
function conversation({ date, text, at, messageDate = null, attachments = 0 }) {
  const parts = text === null ? [] : text.split("\n");
  const message = {
    role: "user",
    ...(messageDate === null ? {} : { create_time: messageDate }),
    ...(text === null ? {} : { content: { parts } }),
    ...(attachments ? { attachments: Array.from({ length: attachments }, () => ({})) } : {}),
  };
  return {
    title: `Working session ${at + 1}`,
    ...(date === null ? {} : { create_time: `${date}T09:00:00Z` }),
    messages: [message, { role: "assistant", content: "Here is a draft." }],
  };
}

/**
 * A synthetic nested export: `blocks` of labelled prompts dealt round-robin over
 * `days`, plus whatever extra conversations a fixture needs.
 *
 * Round-robin rather than block-by-block so every day carries a mix, which is
 * what stops a fixture from accidentally proving that a habit is one afternoon.
 */
export function buildEvalExport({ blocks = [], days = [], extras = [] } = {}) {
  const texts = blocks.flatMap((block) => Array.from({ length: block.count }, () => LABEL[block.prompt].text));
  const conversations = texts.map((text, at) => conversation({ date: days[at % days.length], text, at }));
  return `${JSON.stringify({ conversations: [...conversations, ...extras] }, null, 2)}\n`;
}

